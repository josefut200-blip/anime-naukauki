create table if not exists public.series (
  id bigint generated by default as identity primary key,
  titulo text not null,
  capa_url text not null,
  banner_url text,
  sinopse text,
  ano integer,
  tags text[] default '{}',
  criado_em timestamptz not null default now()
);

create table if not exists public.episodios (
  id bigint generated by default as identity primary key,
  serie_id bigint not null references public.series(id) on delete cascade,
  numero integer not null,
  titulo text,
  video_url text not null,
  criado_em timestamptz not null default now(),
  unique (serie_id, numero)
);

alter table public.series enable row level security;
alter table public.episodios enable row level security;

create policy "visitantes podem ler series" on public.series for select using (true);
create policy "visitantes podem ler episodios" on public.episodios for select using (true);
create policy "admins autenticados podem inserir series" on public.series for insert to authenticated with check (true);
create policy "admins autenticados podem inserir episodios" on public.episodios for insert to authenticated with check (true);
create policy "admins autenticados podem atualizar series" on public.series for update to authenticated using (true) with check (true);
create policy "admins autenticados podem atualizar episodios" on public.episodios for update to authenticated using (true) with check (true);
create policy "admins autenticados podem remover series" on public.series for delete to authenticated using (true);
create policy "admins autenticados podem remover episodios" on public.episodios for delete to authenticated using (true);

